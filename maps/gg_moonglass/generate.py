# ---------------------------------------------------------------- convex shapes (verts, faces)
def prism(poly, z0, z1):
    """Vertical extrusion of a convex 2D polygon."""
    n = len(poly)
    vs = [V(x, y, z0) for x, y in poly] + [V(x, y, z1) for x, y in poly]
    fs = [list(range(n)), list(range(n, 2 * n))] + [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]
    return vs, fs


def extrude(poly3, d):
    """A convex planar polygon swept along vector d."""
    n = len(poly3)
    vs = [np.asarray(p, float) for p in poly3] + [np.asarray(p, float) + d for p in poly3]
    fs = [list(range(n)), list(range(n, 2 * n))] + [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]
    return vs, fs


def slab(poly3, t, outward=None):
    """A flat panel: the polygon is the outer face, thickness t inward (against `outward`, else the polygon normal)."""
    n = unit(newell(poly3, list(range(len(poly3)))))
    if outward is not None and np.dot(n, outward) < 0:
        n = -n
    return extrude([np.asarray(p, float) for p in poly3], -n * t)


def homothetic(poly3, centre, k0, k1):
    """Shell piece between two scaled copies of a polygon about a centre (planar sides)."""
    c = np.asarray(centre, float)
    a = [c + (np.asarray(p) - c) * k0 for p in poly3]
    b = [c + (np.asarray(p) - c) * k1 for p in poly3]
    n = len(poly3)
    return a + b, [list(range(n)), list(range(n, 2 * n))] + [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]


def frustum(poly, z0, z1, k, off=(0, 0)):
    c = np.mean(poly, 0)
    top = [c + (np.asarray(p) - c) * k + off for p in poly]
    n = len(poly)
    vs = [V(x, y, z0) for x, y in poly] + [V(x, y, z1) for x, y in top]
    return vs, [list(range(n)), list(range(n, 2 * n))] + [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]


def beam(p, q, w, h, up=V(0, 0, 1)):
    """A box from p to q, w wide and h deep (towards -up), its top face through p-q."""
    p, q = np.asarray(p, float), np.asarray(q, float)
    d = unit(q - p)
    side = np.cross(d, up)
    if np.linalg.norm(side) < 1e-6:
        side = np.cross(d, V(1, 0, 0))
    side = unit(side) * (w / 2)
    down = unit(np.cross(side, d)) * h
    if np.dot(down, up) > 0:
        down = -down
    quad = [p - side, p + side, p + side + down, p - side + down]
    return extrude(quad, q - p)


def ngon(cx, cy, r, n, rot=0.0):
    return [(cx + r * math.cos(rot + 2 * math.pi * i / n), cy + r * math.sin(rot + 2 * math.pi * i / n)) for i in range(n)]


def obox(cx, cy, ang, length, width):
    """Rectangle footprint centred at (cx, cy), `length` along angle `ang`."""
    ca, sa = math.cos(ang), math.sin(ang)
    hl, hw = length / 2, width / 2
    return [(cx + ca * u - sa * w, cy + sa * u + ca * w) for u, w in ((-hl, -hw), (hl, -hw), (hl, hw), (-hl, hw))]


def polar(r, ang):
    return r * math.cos(ang), r * math.sin(ang)


# ---------------------------------------------------------------- 2D helpers for the spawn checks
def hull2d(pts):
    pts = sorted(set((round(float(x), 3), round(float(y), 3)) for x, y in pts))
    if len(pts) <= 2:
        return pts

    def half(ps):
        out = []
        for p in ps:
            while len(out) >= 2 and ((out[-1][0] - out[-2][0]) * (p[1] - out[-2][1]) - (out[-1][1] - out[-2][1]) * (p[0] - out[-2][0])) <= 0:
                out.pop()
            out.append(p)
        return out
    lo, up = half(pts), half(pts[::-1])
    return lo[:-1] + up[:-1]


def sat_overlap(a, b, eps=0.5):
    for poly in (a, b):
        for i in range(len(poly)):
            x0, y0 = poly[i]
            x1, y1 = poly[(i + 1) % len(poly)]
            nx, ny = y1 - y0, x0 - x1
            pa = [nx * x + ny * y for x, y in a]
            pb = [nx * x + ny * y for x, y in b]
            ln = math.hypot(nx, ny) or 1
            if max(pa) <= min(pb) + eps * ln or max(pb) <= min(pa) + eps * ln:
                return False
    return True


def inside(p, poly):
    s = None
    for i in range(len(poly)):
        x0, y0 = poly[i]
        x1, y1 = poly[(i + 1) % len(poly)]
        c = (x1 - x0) * (p[1] - y0) - (y1 - y0) * (p[0] - x0)
        if abs(c) < 1e-9:
            continue
        if s is None:
            s = c > 0
        elif s != (c > 0):
            return False
    return True


# ---------------------------------------------------------------- layout
class Layout:
    def __init__(self):
        self.solids = []   # {'verts','faces','mats'(per face),'tag','lm','tint','shadows','bake','uv'}
        self.panes = []    # {'verts','faces','mat','kind','health'}
        self.floors = {}   # level z -> list of convex 2D polygons players may spawn on
        self.lights = []

    def solid(self, shape, mats, tag, lm=0, tint=(255, 255, 255), shadows=True, uv=None):
        vs, fs = shape
        vs = [np.asarray(v, float) for v in vs]
        if isinstance(mats, str):
            fm = [mats] * len(fs)
        else:
            fm = []
            for f, n in oriented(vs, fs):
                fm.append(mats['top'] if n[2] > 0.5 else mats['bottom'] if n[2] < -0.5 else mats['side'])
        tools = all(m in (M_SKYBOX, M_CLIP) for m in fm)
        self.solids.append({'verts': vs, 'faces': fs, 'mats': fm, 'tag': tag, 'lm': lm, 'tint': tint,
                            'shadows': shadows, 'bake': not tools and uv is None, 'uv': uv})

    def pane(self, shape, mat, kind):
        vs, fs = shape
        self.panes.append({'verts': [np.asarray(v, float) for v in vs], 'faces': fs, 'mat': mat, 'kind': kind,
                           'health': HEALTH[mat]})

    def floor(self, z, poly):
        self.floors.setdefault(z, []).append([tuple(map(float, p)) for p in poly])


def pick(i, weights):
    """Deterministic material pick for pane i: weights [(mat, w), ...]."""
    h = int(hashlib.md5(f'{NAME}/{i}'.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    acc = 0
    for m, w in weights:
        acc += w
        if h < acc:
            return m
    return weights[-1][0]


def geodesic_hemisphere(v):
    """Octahedron-based geodesic subdivision of the upper unit hemisphere: list of triangles (3 unit vectors)."""
    X, Y, Z = V(1, 0, 0), V(0, 1, 0), V(0, 0, 1)
    tris = []
    for A, B in ((X, Y), (Y, -X), (-X, -Y), (-Y, X)):
        def pt(i, j):
            return unit(A * (v - i - j) + B * i + Z * j)
        for i in range(v):
            for j in range(v - i):
                tris.append((pt(i, j), pt(i + 1, j), pt(i, j + 1)))
                if i + j < v - 1:
                    tris.append((pt(i + 1, j), pt(i + 1, j + 1), pt(i, j + 1)))
    return tris


def dome(L, centre, R, fz, v, kind, weights, strut_mat, strut_w, door=None, clip=False, start=0):
    """A faceted dome: one breakable pane per triangle, a strut on every edge (not the base ring), optional clip shell."""
    c = np.asarray(centre, float)
    tris = []
    for t in geodesic_hemisphere(v):
        pts = [c + V(p[0] * R, p[1] * R, p[2] * R * fz) for p in t]
        if door is not None and door(np.mean(pts, 0)):
            continue
        tris.append(pts)
    edges = {}
    for idx, pts in enumerate(tris):
        out = np.mean(pts, 0) - c
        mat = pick(start + idx, weights)
        L.pane(slab(pts, THICK[mat], outward=out), mat, kind)
        for a in range(3):
            p, q = pts[a], pts[(a + 1) % 3]
            key = tuple(sorted((tuple(np.round(p, 2)), tuple(np.round(q, 2)))))
            edges.setdefault(key, (p, q, []))[2].append(unit(out))
        if clip:
            L.solid(homothetic(pts, c, (R + 12) / R, (R + 20) / R), M_CLIP, 'domeclip')
    for key, (p, q, outs) in edges.items():
        if abs(p[2] - c[2]) < 0.5 and abs(q[2] - c[2]) < 0.5:
            continue   # the base ring sits on the wall or curb
        up = unit(np.sum(outs, 0))
        inset = up * (max(THICK.values()) + 1)
        L.solid(beam(p - inset, q - inset, strut_w, strut_w, up=up), strut_mat, 'strut')
    return len(tris)


