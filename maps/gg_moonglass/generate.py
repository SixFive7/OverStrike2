# ---------------------------------------------------------------- spawns
def footprint(vs):
    return hull2d([(v[0], v[1]) for v in vs])


def inflate(poly, pad):
    """A convex polygon grown by a square of half-size pad (Minkowski sum)."""
    return hull2d([(x + dx, y + dy) for x, y in poly for dx in (-pad, pad) for dy in (-pad, pad)])


def hash_key(key):
    return int(hashlib.md5(repr(key).encode()).hexdigest()[:6], 16)


def pick_spawns(L):
    """Spawn points on solid floors only, clear of every piece, never on or under breakable glass (the big dome excepted)."""
    obstacles = [(footprint(s['verts']), min(v[2] for v in s['verts']), max(v[2] for v in s['verts']))
                 for s in L.solids if s['tag'] not in ('skybox', 'outside', 'ground', 'earth', 'domeclip')]
    glass = [(footprint(p['verts']), min(v[2] for v in p['verts']), max(v[2] for v in p['verts']))
             for p in L.panes if p['kind'] != 'dome']
    cand = {}
    for z, floors in L.floors.items():
        pts = []
        for ix in range(-RW, RW + 1, 32):
            for iy in range(-RW, RW + 1, 32):
                sq = [(ix - 32, iy - 32), (ix + 32, iy - 32), (ix + 32, iy + 32), (ix - 32, iy + 32)]
                if not all(any(inside(c, f) for f in floors) for c in sq + [(ix, iy)]):
                    continue
                if any(z0 < z + 73 and z1 > z + 1 and sat_overlap(sq, fp) for fp, z0, z1 in obstacles):
                    continue
                if any(sat_overlap(sq, fp) and z1 > z - 24 and z0 < z + 900 for fp, z0, z1 in glass):
                    continue
                pts.append((ix, iy))
        cand[z] = pts

    def farthest(pts, k, taken):
        out = []
        for _ in range(k):
            best, bd = None, -1
            for p in pts:
                d = min([math.hypot(p[0] - q[0], p[1] - q[1]) for q in taken + out] or [1e9])
                if d > bd:
                    best, bd = p, d
            if best is None:
                break
            out.append(best)
        return out
    plan = {0: 16, L1: 8}
    dm = {z: farthest(cand.get(z, []), k, []) for z, k in plan.items()}
    t_pts, ct_pts = [], []
    for z, k in ((0, 6), (L1, 2)):
        t_pts += [(p, z) for p in farthest([p for p in cand[z] if p[1] < -150], k, dm[z])]
        ct_pts += [(p, z) for p in farthest([p for p in cand[z] if p[1] > 150], k, dm[z])]
    return dm, t_pts, ct_pts, {z: len(v) for z, v in cand.items()}


