# ---------------------------------------------------------------- generated textures
def fbm(n, beta, seed):
    """Tileable fractal noise: random spectrum with power-law falloff, 0..1."""
    rng = np.random.default_rng(seed)
    k = np.sqrt(np.fft.fftfreq(n)[:, None] ** 2 + np.fft.fftfreq(n)[None, :] ** 2)
    k[0, 0] = 1
    spec = (rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n))) / k ** beta
    spec[0, 0] = 0
    f = np.fft.ifft2(spec).real
    return (f - f.min()) / (f.max() - f.min())


def normal_map(h, strength):
    gx = (np.roll(h, -1, 1) - np.roll(h, 1, 1)) * strength
    gy = (np.roll(h, -1, 0) - np.roll(h, 1, 0)) * strength
    n = np.stack([-gx, gy, np.ones_like(h)], -1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return Image.fromarray(((n * 0.5 + 0.5) * 255).astype(np.uint8))


def make_textures(folder):
    n = 1024
    # lunar regolith: rolling grey dust, small craters, grain
    h = 0.55 * fbm(n, 1.5, 11) + 0.30 * fbm(n, 1.0, 12) + 0.15 * fbm(n, 0.6, 13)
    rng = np.random.default_rng(14)
    yy, xx = np.mgrid[0:n, 0:n]
    for _ in range(26):
        cx, cy, r = rng.uniform(0, n), rng.uniform(0, n), rng.uniform(8, 60)
        dx = np.minimum(np.abs(xx - cx), n - np.abs(xx - cx))
        dy = np.minimum(np.abs(yy - cy), n - np.abs(yy - cy))
        d = np.sqrt(dx ** 2 + dy ** 2) / r
        h += np.where(d < 1, -0.35 * (1 - d ** 2), 0) + 0.18 * np.exp(-((d - 1.0) / 0.18) ** 2)
    h = (h - h.min()) / (h.max() - h.min())
    grain = fbm(n, 0.2, 15)
    g = 0.26 + 0.27 * h + 0.09 * (grain - 0.5)
    col = np.stack([g * 0.98, g * 0.98, g * 1.02], -1)
    Image.fromarray((np.clip(col, 0, 1) * 255).astype(np.uint8)).save(os.path.join(folder, 'regolith_color.png'))
    normal_map(h * 6 + grain * 1.5, 1.0).save(os.path.join(folder, 'regolith_normal.png'))
    # white module panels: 256 px panels with seams and rivets, faint grime
    base = 0.74 + 0.05 * (fbm(n, 1.2, 21) - 0.5)
    hh = np.zeros((n, n))
    seam = ((xx % 256) < 3) | ((yy % 256) < 3)
    base = np.where(seam, 0.36, base)
    hh = np.where(seam, -1.0, hh)
    riv = (((xx % 256) - 12) ** 2 + ((yy % 32) - 16) ** 2 < 9) | (((yy % 256) - 12) ** 2 + ((xx % 32) - 16) ** 2 < 9)
    base = np.where(riv, 0.60, base)
    hh = np.where(riv, 0.8, hh)
    col = np.stack([base, base * 0.995, base * 0.985], -1)
    Image.fromarray((np.clip(col, 0, 1) * 255).astype(np.uint8)).save(os.path.join(folder, 'module_white_color.png'))
    normal_map(hh, 1.2).save(os.path.join(folder, 'module_white_normal.png'))
    # Earth, equirectangular: oceans, continents, ice caps and clouds, lit from one side
    w, hgt = 1024, 512
    lon = (np.arange(w) + 0.5) / w * 2 * np.pi
    lat = (0.5 - (np.arange(hgt) + 0.5) / hgt) * np.pi
    LON, LAT = np.meshgrid(lon, lat)
    land_n = fbm(1024, 1.7, 31)[:hgt, :]
    cloud_n = fbm(1024, 1.3, 32)[:hgt, :]
    land = land_n > 0.56
    ocean = np.stack([0.10 + 0.10 * land_n, 0.32 + 0.16 * land_n, 0.74 + 0.16 * land_n], -1)
    veg = fbm(1024, 1.1, 33)[:hgt, :]
    landc = np.stack([0.36 + 0.34 * veg, 0.52 + 0.16 * veg, 0.24 + 0.10 * veg], -1)
    c = np.where(land[..., None], landc, ocean)
    ice = np.abs(LAT) > np.radians(66) + 0.08 * (land_n - 0.5)
    c = np.where(ice[..., None], 0.96, c)
    cl = np.clip((cloud_n - 0.47) * 3.0, 0, 0.9)[..., None]
    c = c * (1 - cl) + 0.98 * cl
    nx, ny, nz = np.cos(LAT) * np.cos(LON), np.cos(LAT) * np.sin(LON), np.sin(LAT)
    # the side that faces the base (towards -y and down) is the day side; a thin crescent of night on the far edge
    light = np.clip(0.55 + 0.75 * (nx * -0.25 + ny * -0.8 + nz * -0.45), 0.10, 1.1)[..., None]
    Image.fromarray((np.clip(c * light, 0, 1) * 255).astype(np.uint8)).save(os.path.join(folder, 'earth_color.png'))


# ---------------------------------------------------------------- vectors
def V(*a):
    return np.array(a, float)


def unit(a):
    return a / np.linalg.norm(a)


def newell(vs, f):
    n = np.zeros(3)
    for k in range(len(f)):
        a, b = vs[f[k]], vs[f[(k + 1) % len(f)]]
        n += ((a[1] - b[1]) * (a[2] + b[2]), (a[2] - b[2]) * (a[0] + b[0]), (a[0] - b[0]) * (a[1] + b[1]))
    return n


def uv_axes(n):
    ax, ay, az = abs(n[0]), abs(n[1]), abs(n[2])
    if az >= ax and az >= ay:
        return V(1, 0, 0), V(0, -1, 0)
    if ax >= ay:
        return V(0, 1, 0), V(0, 0, -1)
    return V(1, 0, 0), V(0, 0, -1)


def oriented(verts, faces):
    """Faces wound outward (convex solid), with unit normals."""
    c = np.mean(verts, 0)
    out = []
    for f in faces:
        n = newell(verts, f)
        fc = np.mean([verts[i] for i in f], 0)
        if np.dot(n, fc - c) < 0:
            f = list(reversed(f))
            n = -n
        out.append((list(f), unit(n)))
    return out


# ---------------------------------------------------------------- polygon mesh (half-edge CDmePolygonMesh)
def polygon_mesh(verts, faces, face_mats, origin, lm_bias=0, uv_fn=None):
    of = oriented(verts, faces)
    materials = []
    for m in face_mats:
        if m not in materials:
            materials.append(m)
    dest, face, pair, face_hes = [], [], {}, []
    for fi, (f, _) in enumerate(of):
        hes = []
        for k in range(len(f)):
            a, b = f[k], f[(k + 1) % len(f)]
            h = pair.get((a, b))
            if h is None:
                h = len(dest)
                dest += [b, a]
                face += [-1, -1]
                pair[(a, b)] = h
                pair[(b, a)] = h + 1
            assert face[h] == -1, 'non-manifold face loop'
            face[h] = fi
            hes.append(h)
        face_hes.append(hes)
    nh = len(dest)
    assert all(x >= 0 for x in face), 'open mesh'
    nxt = [0] * nh
    for hes in face_hes:
        for k, h in enumerate(hes):
            nxt[h] = hes[(k + 1) % len(hes)]
    vedge = [-1] * len(verts)
    for (a, b), h in pair.items():
        if vedge[a] < 0:
            vedge[a] = h
    tex, nrm, tan = [None] * nh, [None] * nh, [None] * nh
    fscale, fu, fv, fmat = [], [], [], []
    for fi, (f, n) in enumerate(of):
        u, v = uv_axes(n)
        tile = TILE.get(face_mats[fi], 128)
        w = 1 if np.dot(np.cross(n, u), v) > 0 else -1
        if uv_fn is not None:
            uvs = uv_fn([verts[dest[h]] + origin for h in face_hes[fi]])
        for k, h in enumerate(face_hes[fi]):
            wp = verts[dest[h]] + origin
            tex[h] = tuple(uvs[k]) if uv_fn is not None else (float(np.dot(wp, u) / tile), float(np.dot(wp, v) / tile))
            nrm[h] = tuple(n)
            tan[h] = (u[0], u[1], u[2], w)
        fscale.append((tile / 512.0, tile / 512.0))
        fu.append((u[0], u[1], u[2], 0))
        fv.append((v[0], v[1], v[2], 0))
        fmat.append(materials.index(face_mats[fi]))
    nf = len(of)
    return El('CDmePolygonMesh', [
        ('name', 'string', 'meshData'),
        ('vertexEdgeIndices', 'int_array', vedge),
        ('vertexDataIndices', 'int_array', list(range(len(verts)))),
        ('edgeVertexIndices', 'int_array', dest),
        ('edgeOppositeIndices', 'int_array', [h ^ 1 for h in range(nh)]),
        ('edgeNextIndices', 'int_array', nxt),
        ('edgeFaceIndices', 'int_array', face),
        ('edgeDataIndices', 'int_array', [h // 2 for h in range(nh)]),
        ('edgeVertexDataIndices', 'int_array', list(range(nh))),
        ('faceEdgeIndices', 'int_array', [hes[0] for hes in face_hes]),
        ('faceDataIndices', 'int_array', list(range(nf))),
        ('materials', 'string_array', materials),
        ('vertexData', 'element', data_array(len(verts), [stream('position', 'vector3_array', [tuple(v) for v in verts], 3)])),
        ('faceVertexData', 'element', data_array(nh, [stream('texcoord', 'vector2_array', tex, 1),
                                                      stream('normal', 'vector3_array', nrm, 1),
                                                      stream('tangent', 'vector4_array', tan, 1)])),
        ('edgeData', 'element', data_array(nh // 2, [stream('flags', 'int_array', [0] * (nh // 2), 3)])),
        ('faceData', 'element', data_array(nf, [stream('textureScale', 'vector2_array', fscale, 0),
                                                stream('textureAxisU', 'vector4_array', fu, 0),
                                                stream('textureAxisV', 'vector4_array', fv, 0),
                                                stream('materialindex', 'int_array', fmat, 8),
                                                stream('flags', 'int_array', [0] * nf, 3),
                                                stream('lightmapScaleBias', 'int_array', [lm_bias] * nf, 1)])),
        ('subdivisionData', 'element', El('CDmePolygonMeshSubdivisionData', [
            ('subdivisionLevels', 'int_array', [0] * nh), ('streams', 'element_array', [])])),
    ])


