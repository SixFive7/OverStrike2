def rot(x, y, k):
    for _ in range(k % 4):
        x, y = -y, x
    return x, y


def build_layout():
    L = Layout()
    floors_z = LEVELS[1:] + [ROOF]

    # ground floor and the plaza outside (outside is decoration: players never get there)
    L.box((-H, -H, -SLAB), (H, H, 0), {'top': M_FLOOR, 'bottom': M_TRIM, 'side': M_TRIM}, 'floor0')
    L.floors[0] = [(-HI, -HI, HI, HI)]
    for r in rect_minus((-SKY_HALF, -SKY_HALF, SKY_HALF, SKY_HALF), [(-H, -H, H, H)]):
        L.box((r[0], r[1], -32), (r[2], r[3], 0), M_GROUND, 'plaza', lm_bias=-1)

    # slabs of the upper floors and the roof: ring minus ramp holes and glass patches
    for n, z in enumerate(floors_z, start=1):
        holes = [(-A, -A, A, A)] + PATCHES.get(z, [])
        for r in RAMPS:
            if r[0] == n - 1:
                holes.append(ramp_rect(r))
        for r in rect_minus((-H, -H, H, H), holes):
            L.box((r[0], r[1], z - SLAB), (r[2], r[3], z), {'top': M_FLOOR, 'bottom': M_CEIL, 'side': M_TRIM}, f'slab{n}')
        L.floors[z] = [r for r in rect_minus((-HI, -HI, HI, HI), holes)]
        for h in holes:
            L.block(z, h)

    # facade: sill and head bands, columns, and two panes per bay, on every level
    cols = [(-H, -H + 32), (-400, -368), (-144, -112), (112, 144), (368, 400), (H - 32, H)]
    for n, z in enumerate(LEVELS):
        lvl = M_LEVEL[n]
        for side in ('N', 'S', 'E', 'W'):
            sgn = 1 if side in ('N', 'E') else -1
            o0, o1 = (HI, H) if sgn > 0 else (-H, -HI)
            ext = (-H, H) if side in ('N', 'S') else (-HI, HI)

            def put(s0, s1, z0, z1, tag):
                if side in ('N', 'S'):
                    L.box((s0, o0, z0), (s1, o1, z1), lvl, tag)
                else:
                    L.box((o0, s0, z0), (o1, s1, z1), lvl, tag)
            put(ext[0], ext[1], z, z + SILL, 'sill')
            put(ext[0], ext[1], z + HEAD, z + CEIL, 'head')
            for c0, c1 in cols:
                c0, c1 = max(c0, ext[0]), min(c1, ext[1])
                if c1 > c0:
                    put(c0, c1, z + SILL, z + HEAD, 'mullion')
            for (a0, a1), (b0, b1) in zip(cols, cols[1:]):
                bay0, bay1 = a1, b0
                xs = split_even(bay0, bay1, 128)
                for p0, p1 in zip(xs, xs[1:]):
                    q0, q1 = o0 + 6, o0 + 10
                    if side in ('N', 'S'):
                        L.pane((p0, q0, z + SILL), (p1, q1, z + HEAD), M_GLASS, 'window')
                    else:
                        L.pane((q0, p0, z + SILL), (q1, p1, z + HEAD), M_GLASS, 'window')
    # roof parapet
    for side in ('N', 'S', 'E', 'W'):
        if side in ('N', 'S'):
            y0, y1 = (HI, H) if side == 'N' else (-H, -HI)
