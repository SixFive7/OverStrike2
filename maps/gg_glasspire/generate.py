def ramp_rect(r):
    _, axis, a, b, c0, c1 = r
    lo, hi = min(a, b), max(a, b)
    return (lo, c0, hi, c1) if axis == 'x' else (c0, lo, c1, hi)


# glass floor patches (2 x 2 tiles of 128) per floor: corners not used by ramps
def corner(sx, sy):
    x0 = 320 if sx > 0 else -576
    y0 = 320 if sy > 0 else -576
    return (x0, y0, x0 + 256, y0 + 256)


