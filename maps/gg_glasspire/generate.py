def pick_spawns(L):
    """Spawn points on concrete only, never on glass: candidates on a 32-unit grid whose 80 x 80 square stays on a floor
    rect and clear of every blocked rect, then farthest-point picks per level."""
    per_level = {0: 7, LEVELS[1]: 6, LEVELS[2]: 6, LEVELS[3]: 6, ROOF: 5}
    cand = {}
    for z, rects in L.floors.items():
        pts = []
        for ix in range(-HI + 48, HI - 47, 32):
            for iy in range(-HI + 48, HI - 47, 32):
                sq = (ix - 40, iy - 40, ix + 40, iy + 40)
                if not any(r[0] <= sq[0] and r[1] <= sq[1] and r[2] >= sq[2] and r[3] >= sq[3] for r in rects):
                    continue
                if any(overlaps(sq, b) for b in L.blocked.get(z, [])):
                    continue
                pts.append((ix, iy))
        cand[z] = pts

    def farthest(pts, k, taken):
        out = []
        for _ in range(k):
            best, bd = None, -1
            for p in pts:
                d = min([math.hypot(p[0] - q[0], p[1] - q[1]) for q in taken + out] or [1e9])
                if d > bd:
                    best, bd = p, d
            if best is None:
                break
            out.append(best)
        return out

    dm = {}
    for z, k in per_level.items():
        dm[z] = farthest(cand[z], k, [])
    t_pts, ct_pts = [], []
    for z in LEVELS:
        south = [p for p in cand[z] if p[1] < -100]
        north = [p for p in cand[z] if p[1] > 100]
        t_pts += [(p, z) for p in farthest(south, 3 if z in (0, LEVELS[1]) else 2, dm[z])]
        ct_pts += [(p, z) for p in farthest(north, 3 if z in (0, LEVELS[1]) else 2, dm[z])]
    return dm, t_pts, ct_pts


def yaw_to_center(x, y):
    return math.degrees(math.atan2(-y, -x))


