def box_geom(lo, hi):
    vs = [(hi[0] if i & 1 else lo[0], hi[1] if i & 2 else lo[1], hi[2] if i & 4 else lo[2]) for i in range(8)]
    return vs, BOX_FACES


def role_mats(faces, verts, mats):
    """mats: {'top','bottom','side'} -> material; picks by the face's normal."""
    out = []
    c = tuple(sum(v[i] for v in verts) / len(verts) for i in range(3))
    for f in faces:
        n = newell(verts, f)
        fc = tuple(sum(verts[i][k] for i in f) / len(f) for k in range(3))
        if dot(n, sub(fc, c)) < 0:
            n = (-n[0], -n[1], -n[2])
        n = norm(n)
        out.append(mats['top'] if n[2] > 0.5 else mats['bottom'] if n[2] < -0.5 else mats['side'])
    return out


def entity(classname, origin, props, children=(), angles=(0, 0, 0)):
    nid, ref = node_ids()
    ep = El('EditGameClassProps', [('classname', 'string', classname)] + [(k, 'string', str(v)) for k, v in props.items()])
    tail = transform_tail(origin)
    tail[1] = ('angles', 'qangle', angles)
    return El('CMapEntity', [
        ('nodeID', 'int', nid), ('referenceID', 'uint64', ref), ('children', 'element_array', list(children)),
        ('variableTargetKeys', 'string_array', []), ('variableNames', 'string_array', []),
        ('relayPlugData', 'element', El('DmePlugList', [('names', 'string_array', []), ('dataTypes', 'int_array', []),
                                                         ('plugTypes', 'int_array', []), ('descriptions', 'string_array', [])])),
        ('connectionsData', 'element_array', []),
        ('entity_properties', 'element', ep),
        ('hitNormal', 'vector3', (0, 0, 1)), ('isProceduralEntity', 'bool', False),
    ] + tail)


# ---------------------------------------------------------------- layout
class Layout:
    def __init__(self):
        self.solids = []      # {'kind': 'box'|'wedge', 'lo', 'hi', 'mats', 'tag', ...}
        self.panes = []       # {'lo', 'hi', 'mat', 'kind'}
        self.blocked = {}     # level z -> list of 2D rects nobody spawns in
        self.floors = {}      # level z -> list of 2D concrete floor rects (for spawns)

    def box(self, lo, hi, mats, tag, lm_bias=0):
        if isinstance(mats, str):
            mats = {'top': mats, 'bottom': mats, 'side': mats}
        assert all(hi[i] > lo[i] for i in range(3)), (tag, lo, hi)
        self.solids.append({'kind': 'box', 'lo': list(lo), 'hi': list(hi), 'mats': mats, 'tag': tag, 'lm': lm_bias})

    def wedge(self, axis, a, b, c0, c1, z0, z1, mats, tag):
        """Ramp rising along axis ('x'|'y') from coordinate a (height z0) to b (height z1), across [c0, c1]."""
        self.solids.append({'kind': 'wedge', 'axis': axis, 'a': a, 'b': b, 'c0': c0, 'c1': c1, 'z0': z0, 'z1': z1,
                            'mats': mats, 'tag': tag, 'lm': 0})

    def pane(self, lo, hi, mat, kind):
        assert all(hi[i] > lo[i] for i in range(3)), (kind, lo, hi)
        self.panes.append({'lo': list(lo), 'hi': list(hi), 'mat': mat, 'kind': kind})

    def block(self, z, r):
        self.blocked.setdefault(z, []).append(tuple(r))


def rect_minus(outer, holes):
    """outer minus holes, as merged axis-aligned rectangles (x0, y0, x1, y1)."""
    xs = sorted({outer[0], outer[2]} | {min(max(h[i], outer[0]), outer[2]) for h in holes for i in (0, 2)})
    ys = sorted({outer[1], outer[3]} | {min(max(h[i], outer[1]), outer[3]) for h in holes for i in (1, 3)})
    rows = []
    for j in range(len(ys) - 1):
        strips, cur = [], None
        for i in range(len(xs) - 1):
            cx, cy = (xs[i] + xs[i + 1]) / 2, (ys[j] + ys[j + 1]) / 2
            inside = not any(h[0] < cx < h[2] and h[1] < cy < h[3] for h in holes)
            if inside:
                cur = [xs[i], xs[i + 1]] if cur is None else [cur[0], xs[i + 1]]
            elif cur is not None:
                strips.append(tuple(cur))
                cur = None
        if cur is not None:
            strips.append(tuple(cur))
        rows.append((ys[j], ys[j + 1], strips))
    out, open_ = [], {}
    for y0, y1, strips in rows:
        nxt = {}
        for s in strips:
            if s in open_:
                nxt[s] = (open_[s][0], y1)
            else:
                nxt[s] = (y0, y1)
        for s, (a, b) in open_.items():
            if s not in nxt:
                out.append((s[0], a, s[1], b))
        open_ = nxt
    for s, (a, b) in open_.items():
        out.append((s[0], a, s[1], b))
    return out


def overlaps(r, s, pad=0):
    return r[0] < s[2] + pad and s[0] < r[2] + pad and r[1] < s[3] + pad and s[1] < r[3] + pad


def split_even(a, b, maxlen):
    n = max(1, math.ceil((b - a) / maxlen - 1e-9))
    return [a + (b - a) * k / n for k in range(n + 1)]


